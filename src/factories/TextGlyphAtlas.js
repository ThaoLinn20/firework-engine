export function sanitizeText(rawText) {
  if (!rawText || typeof rawText !== 'string') {
    return '';
  }
  let clean = rawText.normalize('NFD').replace(/[\u0300-\u036f]/g, '');
  clean = clean.replace(/đ/g, 'd').replace(/Đ/g, 'D');
  clean = clean.toUpperCase().replace(/[^A-Z0-9\s]/g, ' ');
  return clean.replace(/\s+/g, ' ').trim();
}

export function splitCommentIntoWords(comment, maxWords = 4, maxWordLen = 8) {
  const sanitized = sanitizeText(comment);
  if (!sanitized) {
    return [];
  }
  const words = sanitized.split(/\s+/);
  const result = [];
  for (const w of words) {
    if (!w) {
      continue;
    }
    const trimmed = w.length > maxWordLen ? w.slice(0, maxWordLen) : w;
    result.push(trimmed);
    if (result.length >= maxWords) {
      break;
    }
  }
  return result;
}

export function layoutWord(word, options = {}) {
  if (!word || typeof word !== 'string') {
    return [];
  }
  const cleanWord = sanitizeText(word).replace(/\s+/g, '');
  if (!cleanWord) {
    return [];
  }

  const scale = options.scale ?? 0.38;
  const letterSpacing = options.letterSpacing ?? 1.5;

  const charLayouts = [];
  let currentOffsetX = 0;

  for (let i = 0; i < cleanWord.length; i++) {
    const char = cleanWord[i];
    const glyph = TEXT_GLYPHS[char];
    if (!glyph) {
      continue;
    }

    charLayouts.push({
      glyph,
      offsetX: currentOffsetX
    });
    currentOffsetX += glyph.width + letterSpacing;
  }

  if (charLayouts.length === 0) {
    return [];
  }

  const totalWidth = currentOffsetX - letterSpacing;
  const halfWidth = totalWidth * 0.5;
  const halfHeight = 4.0;

  const points = [];
  for (let i = 0; i < charLayouts.length; i++) {
    const { glyph, offsetX } = charLayouts[i];
    for (let p = 0; p < glyph.points.length; p++) {
      const pt = glyph.points[p];
      const px = (offsetX + pt.x - halfWidth) * scale;
      const py = (pt.y - halfHeight) * scale;
      const pz = (Math.random() - 0.5) * 0.05;
      points.push(new THREE.Vector3(px, py, pz));
    }
  }

  return points;
}

